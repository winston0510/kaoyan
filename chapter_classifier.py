def _match(rules, q):
    for ch, kws in rules:
        for kw in kws:
            if kw in q:
                return ch
    return None

def classify_math2(question, is_linear):
    q = question or ''
    if is_linear:
        hit = _match(LA_RULES, q)
        if hit:
            return hit
        hit = _match(GS_RULES, q)
        if hit:
            return hit
        return '综合'
    hit = _match(GS_RULES, q)
    if hit:
        return hit
    hit = _match(LA_RULES, q)
    if hit:
        return hit
    return '第7章 综合应用'

def fix_chapter(subject, chapter, question):
    ch = (chapter or '').strip()
    if subject == 'circuit':
        return CIRCUIT_RENAME.get(ch, ch)
    if subject == 'english2':
        return ENGLISH2_RENAME.get(ch, ch)
    if subject == 'math2':
        if ch in MATH2_GAOSHU_GENERIC:
            return classify_math2(question, False)
        if ch in MATH2_XIANDAI_GENERIC:
            return classify_math2(question, True)
    return ch

const fs = require('fs');
const Q = [];
const seen = new Set();

function ri(min, max) { return Math.floor(Math.random() * (max - min + 1)) + min; }
function shuffle(arr) { let c = [...arr]; for (let i = c.length-1; i>0; i--) { let j = Math.floor(Math.random()*(i+1)); [c[i],c[j]]=[c[j],c[i]]; } return c; }
function esc(s) { return String(s).replace(/'/g, "''"); }

function mk(correct, wrongs) {
  let opts = [correct];
  for (let w of wrongs) { if (w !== correct && !opts.includes(w)) opts.push(w); }
  while (opts.length < 4) { let v = String(ri(1,99)); if (!opts.includes(v)) opts.push(v); }
  opts = opts.slice(0,4);
  let sh = shuffle(opts);
  let idx = sh.indexOf(correct);
  let ans = 'ABCD'[idx];
  let formatted = sh.map((o,i) => `${'ABCD'[i]}. ${o}`);
  return { o: JSON.stringify(formatted), a: ans };
}

function add(ch, t, q, o, a, e, d) {
  if (seen.has(q)) return;
  seen.add(q);
  Q.push({ ch, t, q, o, a, e, d });
}

// single-choice question helper
function sq(ch, q, c, w1, w2, w3, e, d) {
  let { o, a } = mk(c, [w1, w2, w3]);
  add(ch, 'single', q, o, a, e, d);
}

// judge question helper
function jq(ch, q, isTrue, e, d) {
  add(ch, 'judge', q, '["A. 正确","B. 错误"]', isTrue ? 'A' : 'B', e, d);
}

